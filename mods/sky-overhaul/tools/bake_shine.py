"""Bakes src/engine/shine_registers.inc: for every retail pixel shader that takes a material's shine,
the CRC-32 of its bytecode and the constant register of each shine parameter it reads, so a draw
can be made wet by its own lighting. Vehicles keep theirs as a clean and a broken colour.

    python tools/bake_shine.py [<extracted shadersobj folder>]

The folder holds the D3D9 shader objects, by default the main tree's tmp/gamefiles/shadersobj. Each
object is a binding table of CRC-32 parameter names in front of the bytecode the device hands back.
See docs/docs/file-formats/shader-objects.md. Skin, hair, cloth, leaves and the weapons are left
out.
"""
import struct
import sys
import textwrap
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "scripts"))
from modstatus import MAIN_TREE  # noqa: E402

MAGIC = b"\x8d\x06\x08\x02"
PIXEL_SHADER_3 = b"\x00\x03\xff\xff"
CONSTANT = 8
SAMPLER = 12

# The registers a row of the table holds, in order; DetailSpecularColor also holds its count.
FIELDS = ["SpecularColorBase", "SpecularColor1", "SpecularPower", "ReflectionPower",
          "DetailSpecularColor", "SpecularShininess", "SpecularIntensity", "NormalOffsetScale",
          "ReflectionNormalOffsetScale", "FresnelBias", "FresnelPower", "SpecularColorBaseClean",
          "SpecularColor1Clean", "SpecularColorBaseBroken", "SpecularColor1Broken"]
SHINE = set(FIELDS)
# The sampler the water reads its waves from, kept for water alone.
WATER_NORMAL = "NormalTexture"
# Parameters only skin, hair, cloth, leaf and weapon materials take.
EXCLUDED = {"SkinColor", "SubsurfaceColor", "FresnelColor", "FabricTiling", "BaseColor1",
            "SSSStrength", "SSSHighLight", "Reliability"}
NONE = 0xFF


def crc(name):
    return zlib.crc32(name.encode()) & 0xFFFFFFFF


BY_CRC = {crc(name): name for name in SHINE | EXCLUDED | {WATER_NORMAL}}


def read(path):
    """The object's constant rows by name and its bytecode's CRC-32, or None if it is no ps_3_0."""
    data = path.read_bytes()
    if len(data) < 12 or data[:4] != MAGIC:
        return None
    offset, = struct.unpack_from("<H", data, 4)
    code = data[offset:]
    if code[:4] != PIXEL_SHADER_3:
        return None
    rows = {}
    for i in range(data[9]):
        name_crc, packed, count, _ = struct.unpack_from("<IHBB", data, 12 + 8 * i)
        name = BY_CRC.get(name_crc)
        kind = SAMPLER if name == WATER_NORMAL else CONSTANT
        if name is not None and count > 0 and packed & 63 == kind:
            rows[name] = (packed >> 6, count)
    return rows, zlib.crc32(code) & 0xFFFFFFFF


def entry(rows):
    registers = [rows[name][0] if name in rows else NONE for name in FIELDS]
    detail = FIELDS.index("DetailSpecularColor")
    registers.insert(detail + 1, rows["DetailSpecularColor"][1] if "DetailSpecularColor" in rows else 0)
    water = "FresnelBias" in rows and WATER_NORMAL in rows
    registers.append(rows[WATER_NORMAL][0] if water else NONE)
    return tuple(registers)


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else MAIN_TREE / "tmp/gamefiles/shadersobj"
    table = {}
    conflicts = 0
    seen = 0
    for path in source.rglob("*"):
        if not path.is_file():
            continue
        parsed = read(path)
        if parsed is None:
            continue
        seen += 1
        rows, code_crc = parsed
        if not SHINE & rows.keys() or EXCLUDED & rows.keys():
            continue
        row = entry(rows)
        if table.get(code_crc, row) != row:
            conflicts += 1
            continue
        table[code_crc] = row
    if seen == 0:
        sys.exit(f"no pixel shader objects under {source}")

    columns = ", ".join(FIELDS[:5] + ["its register count"] + FIELDS[5:])
    described = textwrap.wrap(
        "The pixel shaders that take a material's shine, by the CRC-32 of their bytecode in rising "
        f"order, and the register of: {columns}; then water's {WATER_NORMAL} sampler; 255 where the "
        "shader takes none.", 96)
    lines = [
        "// Generated by tools/bake_shine.py from the retail shader objects; do not edit.",
        *("// " + line for line in described),
        f"constexpr int kShineFields = {len(FIELDS) + 2};",
        "struct ShineShader {",
        "    uint32_t crc;",
        "    uint8_t registers[kShineFields];",
        "};",
        f"constexpr ShineShader kShineShaders[{len(table)}] = {{",
    ]
    for code_crc in sorted(table):
        lines.append("    {0x%08Xu, {%s}}," % (code_crc, ", ".join(str(r) for r in table[code_crc])))
    lines.append("};")
    out = HERE.parent / "src/engine/shine_registers.inc"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    water = sum(1 for row in table.values() if row[-1] != NONE)
    print(f"{seen} pixel shaders read, {len(table)} take shine ({water} water), "
          f"{conflicts} bytecode shared with different registers left out. Wrote {out}")


if __name__ == "__main__":
    main()
