# Halts the turn when a Ghidra MCP call comes back with a connection error.
# Registered on PostToolUse with matcher mcp__ghidra__.*
#
# The bridge reports an unreachable Ghidra as a SUCCESSFUL tool result whose body is
# the error text ("Request failed: HTTPConnectionPool(...) ... actively refused it"),
# so PostToolUse - not just PostToolUseFailure - has to be inspected.

$ErrorActionPreference = 'Stop'

$raw = [Console]::In.ReadToEnd()
if (-not $raw) { exit 0 }

try { $payload = $raw | ConvertFrom-Json } catch { exit 0 }

# Only inspect what came BACK from the tool, never the arguments we sent.
function Get-Text($value) {
    if ($null -eq $value) { return '' }
    if ($value -is [string]) { return $value }
    return ($value | ConvertTo-Json -Depth 10 -Compress)
}

$response = Get-Text $payload.tool_response
$toolError = Get-Text $payload.tool_error

# Bridge-specific transport failures. Deliberately narrow: list_strings dumps raw
# binary strings, and FarCry2's netcode has literals like "Connection refused".
$bridgeSignatures = @(
    'HTTPConnectionPool'
    'Max retries exceeded'
    'Failed to establish a new connection'
    'NewConnectionError'
    'ConnectTimeoutError'
    'WinError 10061'
)

# tool_error is generated by the harness, never by the target binary, so generic
# transport wording is safe to match there.
$transportSignatures = $bridgeSignatures + @(
    'Connection refused'
    'ECONNREFUSED'
    'Connection closed'
    'not connected'
    'MCP server'
)

function Test-Signatures($text, $signatures) {
    if (-not $text) { return $false }
    foreach ($sig in $signatures) {
        if ($text -like "*$sig*") { return $true }
    }
    return $false
}

$hit = (Test-Signatures $response $bridgeSignatures) -or (Test-Signatures $toolError $transportSignatures)
if (-not $hit) { exit 0 }

$stop = @(
    'Ghidra MCP bridge is unreachable - http://127.0.0.1:8080 refused the connection.'
    'Start Ghidra, open the FC2 project, and confirm the GhidraMCP plugin server is listening, then re-run the request.'
) -join ' '

@{ continue = $false; stopReason = $stop; systemMessage = $stop } | ConvertTo-Json -Compress
exit 0
